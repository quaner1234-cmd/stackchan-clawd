"""Resize approved originals for native LVGL flash assets; never alter originals."""
import hashlib
import json
from pathlib import Path
import struct
import zlib
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'device/art-gallery'
HEADER=ROOT/'device/upstream/firmware/main/hal/clawd_artwork_data.h'
ITEMS=[('scream','the-scream-xiaoke-v1.png'),('pearl','pearl-earring-xiaoke-v1.png'),('starry','starry-night-xiaoke-v1.png')]


def main():
    ASSETS.mkdir(exist_ok=True)
    header=['// Generated by tools/build-art-gallery.py from approved artwork-previews originals.',
            '#pragma once','#include <lvgl.h>','#include <cstdint>']
    manifest=[]
    review=Image.new('RGB',(960,240))
    for index,(name,filename) in enumerate(ITEMS):
        source=ROOT/'artwork-previews'/filename
        with Image.open(source) as image:
            assert image.width*3==image.height*4,'Expected approved 4:3 original'
            image=image.convert('RGB').resize((320,240),Image.Resampling.LANCZOS)
        rgb=bytearray()
        for r,g,b in struct.iter_unpack('BBB',image.tobytes()):rgb.extend(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)))
        raw=bytes(rgb);(ASSETS/f'{name}.rgb565').write_bytes(raw)
        # Review the exact RGB565 quantization the LCD will display.
        pixels=bytearray()
        for value, in struct.iter_unpack('<H',raw):pixels.extend((((value>>11)&31)*255//31,((value>>5)&63)*255//63,(value&31)*255//31))
        actual=Image.frombytes('RGB',(320,240),bytes(pixels))
        actual.save(ASSETS/f'{name}-320x240.png');review.paste(actual,(index*320,0))
        header.append(f'alignas(4) static const uint8_t clawd_art_{name}[] = {{')
        header.extend('    '+','.join(f'0x{v:02x}' for v in raw[i:i+32])+',' for i in range(0,len(raw),32))
        header.append('};')
        manifest.append(dict(name=name,source=str(source.relative_to(ROOT)).replace('\\','/'),
            source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),width=320,height=240,format='RGB565_LE',
            bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest(),crc32=zlib.crc32(raw),duration_ms=15000))
    header.extend(['inline lv_image_dsc_t clawd_art_descriptor(const uint8_t* pixels) {',
        '    lv_image_dsc_t d{};d.header.magic=LV_IMAGE_HEADER_MAGIC;d.header.cf=LV_COLOR_FORMAT_RGB565;',
        '    d.header.w=320;d.header.h=240;d.header.stride=640;d.data_size=320*240*2;d.data=pixels;return d;','}',
        'inline const lv_image_dsc_t* clawd_art_image(unsigned index) {',
        '    static const lv_image_dsc_t images[]={clawd_art_descriptor(clawd_art_scream),clawd_art_descriptor(clawd_art_pearl),clawd_art_descriptor(clawd_art_starry)};',
        '    return &images[index<3?index:0];','}'])
    HEADER.write_text('\n'.join(header)+'\n',encoding='utf-8')
    review.save(ASSETS/'gallery-320x240-review.png')
    (ASSETS/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(dict(images=len(ITEMS),flash_pixel_bytes=sum(i['bytes'] for i in manifest),review=str(ASSETS/'gallery-320x240-review.png'))))


if __name__=='__main__':main()
